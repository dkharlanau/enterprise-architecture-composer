function statusForFinding(finding) {
  if (finding.severity === 'error') return 'danger';
  if (finding.severity === 'warning') return 'warning';
  return 'neutral';
}

function tags(layer, sourceId, extra = []) {
  return [`layer:${layer}`, `source:${sourceId}`, ...extra];
}

export function toVisualWorkbench(result, options = {}) {
  const title = options.title ?? 'Composed enterprise architecture';
  const groups = [
    { id: 'business', label: 'Business', kind: 'lane', order: 1 },
    { id: 'applications', label: 'Applications & platforms', kind: 'lane', order: 2 },
    { id: 'data', label: 'Data', kind: 'lane', order: 3 },
    { id: 'decisions', label: 'Open decisions', kind: 'lane', order: 4 }
  ];

  const capabilityNodes = result.blueprint.capabilities.map((item) => ({
    id: item.id,
    label: item.name,
    type: 'step',
    subtitle: 'Business capability',
    description: item.description,
    group: 'business',
    status: 'neutral',
    tags: tags('capability', item.id, ['capability'])
  }));

  const systemNodes = result.blueprint.systems.map((item) => ({
    id: item.id,
    label: item.name,
    type: 'system',
    subtitle: item.state === 'current' ? 'Current responsibility' : 'Target responsibility',
    description: item.description,
    group: 'applications',
    status: item.state === 'current' ? 'success' : 'neutral',
    tags: tags('system', item.id, [`state:${item.state}`, `intent:${item.intent}`])
  }));

  const dataNodes = result.blueprint.dataObjects.map((item) => ({
    id: item.id,
    label: item.name,
    type: 'data',
    subtitle: item.owner ? `Owner: ${item.owner}` : 'Owner unresolved',
    description: item.description,
    group: 'data',
    status: item.owner ? 'neutral' : 'warning',
    tags: tags('data', item.id, [item.owner ? 'ownership:defined' : 'ownership:missing'])
  }));

  const findingNodes = result.findings.map((item) => ({
    id: item.id,
    label: item.nextDecision,
    type: item.kind === 'security-decision' ? 'risk' : 'decision',
    subtitle: item.message,
    group: 'decisions',
    status: statusForFinding(item),
    tags: tags('finding', item.id, [`severity:${item.severity}`])
  }));

  const integrationEdges = result.blueprint.integrations.map((item) => ({
    from: item.source,
    to: item.target,
    label: `${item.name} · ${item.patternName}`,
    type: item.mode === 'async' ? 'data' : 'flow',
    status: 'neutral',
    note: `${item.id}; rules: ${item.ruleIds.join(', ')}`
  }));

  const ownershipEdges = result.blueprint.dataObjects
    .filter((item) => item.owner)
    .map((item) => ({
      from: item.owner,
      to: item.id,
      label: 'owns',
      type: 'relation',
      status: 'muted'
    }));

  const findingEdges = result.findings.flatMap((finding) =>
    finding.objectIds
      .filter((id) => [...result.blueprint.systems, ...result.blueprint.dataObjects, ...result.blueprint.capabilities].some((item) => item.id === id))
      .map((id) => ({
        from: id,
        to: finding.id,
        label: 'requires decision',
        type: 'exception',
        status: statusForFinding(finding)
      }))
  );

  return {
    visual: {
      version: 1,
      title,
      description: 'Deterministic projection generated by Enterprise Architecture Composer. Node IDs preserve Composer source IDs.',
      kind: 'system-flow',
      direction: 'right',
      theme: 'paper',
      density: 'compact',
      groups,
      nodes: [...capabilityNodes, ...systemNodes, ...dataNodes, ...findingNodes].sort((a, b) => a.id.localeCompare(b.id)),
      edges: [...integrationEdges, ...ownershipEdges, ...findingEdges].sort((a, b) => `${a.from}:${a.to}:${a.label}`.localeCompare(`${b.from}:${b.to}:${b.label}`)),
      views: [
        {
          id: 'executive',
          title: 'Executive architecture',
          focus: 'executive',
          kind: 'system-flow',
          includeNodeTypes: ['step', 'system'],
          excludeEdgeTypes: ['exception']
        },
        {
          id: 'integration',
          title: 'Integration landscape',
          focus: 'flow',
          kind: 'system-flow',
          includeNodeTypes: ['system'],
          includeEdgeTypes: ['flow', 'data']
        },
        {
          id: 'data',
          title: 'Data ownership',
          focus: 'data',
          kind: 'data-flow',
          includeNodeTypes: ['system', 'data'],
          includeEdgeTypes: ['relation', 'data']
        },
        {
          id: 'exceptions',
          title: 'Open architecture decisions',
          focus: 'exceptions',
          kind: 'dependency-map',
          includeNodeTypes: ['system', 'data', 'decision', 'risk'],
          includeEdgeTypes: ['exception']
        }
      ]
    }
  };
}

function yamlScalar(value) {
  return JSON.stringify(value);
}

function yamlArray(values, indent) {
  if (!values?.length) return `${' '.repeat(indent)}[]`;
  return values.map((value) => `${' '.repeat(indent)}- ${yamlScalar(value)}`).join('\n');
}

export function visualWorkbenchMarkdown(projection) {
  const json = JSON.stringify(projection, null, 2);
  return `---\n# This JSON-shaped YAML is intentionally emitted without layout coordinates.\nvisual: ${json.replace(/^\{\n  "visual": /, '').replace(/\n\}$/, '').trim()}\n---\n\nGenerated by Enterprise Architecture Composer.\n`;
}
